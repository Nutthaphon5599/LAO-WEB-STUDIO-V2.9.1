-- ---------------------------------------------------------------------
-- UPDATED-AT TRIGGERS
-- ---------------------------------------------------------------------
do $$
declare
  t text;
begin
  foreach t in array array[
    'projects','pricing','leads','employees','quotations',
    'appointments','tasks','company_settings','services',
    'roles_permissions','profiles','invoices'
  ]
  loop
    execute format(
      'drop trigger if exists %I on public.%I',
      t || '_updated_at', t
    );
    execute format(
      'create trigger %I before update on public.%I
       for each row execute function public.lws_set_updated_at()',
      t || '_updated_at', t
    );
  end loop;
end $$;

-- ---------------------------------------------------------------------
-- PAYMENT STATUS AUTOMATION
-- ---------------------------------------------------------------------
create or replace function public.lws_refresh_invoice_status(
  p_invoice_id uuid
)
returns void
language plpgsql
security definer
set search_path=public
as $$
declare
  v_paid numeric(14,2);
  v_total numeric(14,2);
begin
  select total into v_total
  from public.invoices where id=p_invoice_id;

  select coalesce(sum(amount),0) into v_paid
  from public.payments where invoice_id=p_invoice_id;

  update public.invoices
  set status=case
    when v_total > 0 and v_paid >= v_total then 'paid'
    when v_paid > 0 then 'partially_paid'
    when due_date < current_date
      and status not in ('paid','cancelled') then 'overdue'
    else status
  end,
  updated_at=now()
  where id=p_invoice_id;
end;
$$;

create or replace function public.lws_payment_status_trigger()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  perform public.lws_refresh_invoice_status(
    coalesce(new.invoice_id,old.invoice_id)
  );
  return coalesce(new,old);
end;
$$;

drop trigger if exists payments_refresh_invoice
on public.payments;
create trigger payments_refresh_invoice
after insert or update or delete on public.payments
for each row execute function public.lws_payment_status_trigger();

-- ---------------------------------------------------------------------
-- ROW LEVEL SECURITY
-- ---------------------------------------------------------------------
do $$
declare
  t text;
  p record;
begin
  foreach t in array array[
    'projects','pricing','leads','employees','quotations',
    'appointments','client_files','tasks','activities',
    'notifications','company_settings','services',
    'roles_permissions','profiles','invoices','payments',
    'project_updates'
  ]
  loop
    execute format(
      'alter table public.%I enable row level security', t
    );

    for p in
      select policyname from pg_policies
      where schemaname='public' and tablename=t
    loop
      execute format(
        'drop policy if exists %I on public.%I',
        p.policyname,t
      );
    end loop;
  end loop;
end $$;

