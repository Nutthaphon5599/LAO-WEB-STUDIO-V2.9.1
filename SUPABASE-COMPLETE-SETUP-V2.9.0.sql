create or replace function public.lws_handle_new_user()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  insert into public.profiles(id,full_name,email,role)
  values(
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name',''),
    new.email,
    case
      when not exists (
        select 1 from public.profiles where role='owner'
      ) then 'owner'
      else coalesce(new.raw_user_meta_data->>'role','customer')
    end
  )
  on conflict (id) do update set
    email=excluded.email,
    updated_at=now();
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.lws_handle_new_user();

-- Backfill users created before this setup. The oldest account becomes
-- owner only when no owner profile currently exists.
insert into public.profiles(id,full_name,email,role)
select
  u.id,
  coalesce(u.raw_user_meta_data->>'full_name',''),
  u.email,
  case
    when row_number() over(order by u.created_at)=1
      and not exists(select 1 from public.profiles where role='owner')
    then 'owner'
    else 'customer'
  end
from auth.users u
on conflict (id) do update set
  email=excluded.email,
  updated_at=now();

