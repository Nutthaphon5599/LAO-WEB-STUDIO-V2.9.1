with check(public.is_staff());

-- ---------------------------------------------------------------------
-- STORAGE
-- ---------------------------------------------------------------------
insert into storage.buckets(id,name,public)
values
  ('portfolio','portfolio',true),
  ('client-files','client-files',false)
on conflict(id) do update set
  public=excluded.public;

-- Remove only Lao Web Studio policies by their exact names.
drop policy if exists lws_portfolio_public_read
on storage.objects;
drop policy if exists lws_portfolio_staff_insert
on storage.objects;
drop policy if exists lws_portfolio_staff_update
on storage.objects;
drop policy if exists lws_portfolio_staff_delete
on storage.objects;
drop policy if exists lws_client_files_staff
on storage.objects;

create policy lws_portfolio_public_read
on storage.objects for select to anon,authenticated
using(bucket_id='portfolio');

create policy lws_portfolio_staff_insert
on storage.objects for insert to authenticated
with check(
  bucket_id='portfolio' and public.is_staff()
);

create policy lws_portfolio_staff_update
on storage.objects for update to authenticated
using(bucket_id='portfolio' and public.is_staff())
with check(bucket_id='portfolio' and public.is_staff());

create policy lws_portfolio_staff_delete
on storage.objects for delete to authenticated
using(bucket_id='portfolio' and public.is_staff());

create policy lws_client_files_staff
on storage.objects for all to authenticated
using(bucket_id='client-files' and public.is_staff())
with check(bucket_id='client-files' and public.is_staff());

